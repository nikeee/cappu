class IntConv {

  long toLong(int arg0) {
    return (long) arg0;
  }

  float toFloat(int arg0) {
    return (float) arg0;
  }

  double toDouble(int arg0) {
    return (double) arg0;
  }

  byte toByte(int arg0) {
    return (byte) arg0;
  }

  char toChar(int arg0) {
    return (char) arg0;
  }

  short toShort(int arg0) {
    return (short) arg0;
  }
}
