class NewArray {

  int[] prim(int arg0) {
    return new int[arg0];
  }

  java.lang.String[] ref(int arg0) {
    return new java.lang.String[arg0];
  }

  boolean[] bools(int arg0) {
    return new boolean[arg0];
  }

  long[] longs(int arg0) {
    return new long[arg0];
  }

  int[][] multi(int arg0, int arg1) {
    return new int[arg0][arg1];
  }
}
